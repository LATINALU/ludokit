export const modelo = (id: string): Modelo => {
  const m = MODELOS.find((x) => x.id === id);
  if (!m) throw new Error(`Modelo desconocido: ${id}. Disponibles: ${MODELOS.map((x) => x.id).join(", ")}`);
  return m;
};

export const modelosBase = (): Modelo[] => MODELOS.filter((m) => m.tipo === "base");
export const modificadores = (): Modelo[] => MODELOS.filter((m) => m.tipo === "modificador");
